def _parse_kml_forgiving(raw):
    """Parse KML that may not be strictly well-formed.

    Real-world exports (e.g. ArcGIS "Export To KMZ") sometimes reference
    undeclared namespace prefixes like ``xsi:schemaLocation``, which the strict
    stdlib parser rejects ("unbound prefix"). Fall back to lxml's recovering
    parser, then round-trip through tostring so the rest of the code keeps
    working with plain xml.etree elements.
    """
    try:
        return ET.fromstring(raw)
    except ET.ParseError:
        from lxml import etree as _lxml

        parser = _lxml.XMLParser(recover=True, ns_clean=True, huge_tree=True)
        root = _lxml.fromstring(raw, parser=parser)
        if root is None:
            raise
        # recover=True keeps attributes whose prefix was never declared
        # (stored with a literal "prefix:name" key); drop them so the
        # re-serialized document is well-formed for the stdlib parser.
        for el in root.iter():
            if not isinstance(el.tag, str):
                continue
            for k in list(el.attrib):
                if not k.startswith('{') and ':' in k:
                    del el.attrib[k]
        return ET.fromstring(_lxml.tostring(root))


def extract_line_placemarks(kml_or_kmz_bytes):
    """All LineStrings in a KMZ/KML (document order) as line Placemarks.

    Handles MultiGeometry, placemarks outside folders, inline styles,
    shared styles, and StyleMap (normal key). Color is the KML aabbggrr
    LineStyle color string, or None if the document does not specify one.
    """
    raw = kml_or_kmz_bytes
    if isinstance(raw, (bytes, bytearray)) and raw[:2] == b'PK':
        raw = _read_kml_bytes(bytes(raw))
    root = _parse_kml_forgiving(raw)

    styles, stylemaps = {}, {}
    for el in root.iter():
        tag = _ln(el)
        if tag == 'Style' and el.get('id'):
            styles[el.get('id')] = el
        elif tag == 'StyleMap' and el.get('id'):
            for pair in el.findall('k:Pair', KNS):
                if _first_text(pair, 'k:key') in (None, 'normal'):
                    su = _first_text(pair, 'k:styleUrl')
                    if su:
                        stylemaps[el.get('id')] = su.lstrip('#')
                    st_inline = pair.find('k:Style', KNS)
                    if st_inline is not None:
                        styles['\x00map:' + el.get('id')] = st_inline
                        stylemaps.setdefault(el.get('id'), '\x00map:' + el.get('id'))
                    break

    def resolve_color(pm):
        if pm is None:
            return None
        color = _style_line_color(pm.find('k:Style', KNS))
        if color:
            return color
        su = _first_text(pm, 'k:styleUrl')
        seen = set()
        while su:
            sid = su.lstrip('#')
            if sid in seen:
                break
            seen.add(sid)
            if sid in styles:
                return _style_line_color(styles[sid])
            su = stylemaps.get(sid)
        return None

    parent = {c: p for p in root.iter() for c in p}

    def enclosing_placemark(el):
        while el is not None:
            if _ln(el) == 'Placemark':
                return el
            el = parent.get(el)
        return None

    out = []
    for ls in root.iter():
        if _ln(ls) != 'LineString':
            continue
        coords_el = ls.find('k:coordinates', KNS)
        if coords_el is None or not coords_el.text:
            continue
        coords = _coords(coords_el.text)
        if len(coords) < 2:
            continue
        pm = enclosing_placemark(ls)
        name = _first_text(pm, 'k:name') if pm is not None else None
        out.append(Placemark(name, 'line', coords, None, resolve_color(pm)))
    return out


def generate_centerline_dmt(line_placemarks):
    """Build a .dmt whose Centerline draw layer holds the given lines.

    Mirrors generate_dmt() exactly, but takes pre-extracted line placemarks
    (possibly from several KMZs) instead of one foldered KMZ, writes them all
    into the Centerline layer, and makes Centerline the active draw layer.
    Each line keeps its own KML color; lines without a color are red.
    """
    lns = [p for p in line_placemarks if p.kind == 'line' and len(p.coords) >= 2]
    if not lns:
        raise ValueError('No LineString geometry to write into the .dmt.')

    tpl = OLE(_template_bytes())
    streams = tpl.stream_map()

    t = LineLayerTemplate(streams['Centerline41 (4)'])

    def color_fn(pm):
        rgb = kml_color_to_rgb(pm.color)
        return rgb if rgb else (255, 0, 0)

    new_streams = {'Centerline41 (4)': t.build(lns, color_fn)}

    # Rebuild the other three draw layers as EMPTY (zero objects) so none of
    # the template's example content (AGM symbols, key-map notes, access
    # lines) shows up in the output — only the centerline geometry remains.
    new_streams['Final AGMs68'] = PointLayerTemplate(
        streams['Final AGMs68'], has_symbol=True).build([], None)
    new_streams['notes (26)'] = PointLayerTemplate(
        streams['notes (26)'], has_symbol=False).build([], None)
    new_streams['Combined Access Files1 (11)'] = LineLayerTemplate(
        streams['Combined Access Files1 (11)']).build([], None)

    rename = {
        'Final AGMs68': 'AGMs',
        'Combined Access Files1 (11)': 'Access',
        'notes (26)': 'Notes',
        'Centerline41 (4)': 'Centerline',
    }
    order = ['Centerline41 (4)', 'notes (26)',
             'Combined Access Files1 (11)', 'Final AGMs68']
    layer_names = [rename[o] for o in order]
    new_streams['Annotate.Filenames'] = _filenames_stream('Centerline', layer_names)
    new_streams['Annotate.ActiveFilenames'] = _active_stream('Centerline')
    return write_ole(tpl, new_streams, rename=rename)
