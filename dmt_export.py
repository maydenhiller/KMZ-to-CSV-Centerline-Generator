"""
DeLorme .dmt export for the KMZ-to-CSV Centerline Generator.

Core machinery (OLE compound-file writer, embedded DeLorme template,
point/line layer templates, coordinate encoding) is copied byte-for-byte
from the proven KMZ-To-DMT-Generator app (github.com/maydenhiller/KMZ-To-DMT-Generator,
blob 52b381e). Only the extraction + centerline-only entry point below are new.

The generated .dmt contains the standard four draw layers (AGMs, Access,
Centerline, Notes); all centerline geometry is written into the Centerline
draw layer (visible in the Draw tab), one polyline per KML LineString, each
keeping its own KML color (fallback red).
"""

